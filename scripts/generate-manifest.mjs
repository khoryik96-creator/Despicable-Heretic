import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const contentRoot = path.join(root, 'src', 'content');
const titlesPath = path.join(root, 'src', 'domain', 'seasonTitles.json');
const outputPath = path.join(root, 'src', 'generated', 'manuscriptChapterManifest.ts');

const seasonTitles = JSON.parse(await readFile(titlesPath, 'utf8'));

function clean(text) {
  return String(text)
    .replace(/\[\[(?:Ryn|Lucy)\]\]\s*/g, '')
    .replace(/\*\*/g, '')
    .replace(/^#+\s*/gm, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function shorten(text, max) {
  if (text.length <= max) return text;
  const clipped = text.slice(0, max - 1).replace(/\s+\S*$/, '');
  return `${clipped || text.slice(0, max - 1)}…`;
}

function deriveTitle(body, chapter) {
  const firstParagraph = clean(String(body).split(/\n{2,}/)[0] ?? '');
  return firstParagraph ? shorten(firstParagraph, 82) : `Chapter ${chapter}`;
}

function deriveSummary(body) {
  const summary = String(body)
    .split(/\n{2,}/)
    .map(clean)
    .filter(Boolean)
    .slice(0, 3)
    .join(' ');
  return shorten(summary, 235);
}

function parseBodies(text, season) {
  const bodies = new Map();
  const pattern = /^\s*(\d+)\s*:\s*String\.raw`([\s\S]*?)`\s*(?:,|\n};)/gm;
  let match;
  while ((match = pattern.exec(text))) bodies.set(Number(match[1]), match[2]);
  const numbers = [...bodies.keys()].sort((a, b) => a - b);
  const expected = Array.from({ length: 10 }, (_, i) => i + 1);
  if (numbers.length !== 10 || expected.some((number) => !bodies.has(number))) {
    throw new Error(`Season ${season} must contain chapter bodies 1-10 before manifest generation; found [${numbers.join(', ')}].`);
  }
  return bodies;
}

const seasonDirs = (await readdir(contentRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory() && /^season-\d{2}$/.test(entry.name))
  .map((entry) => Number(entry.name.slice(-2)))
  .filter((season) => season >= 26)
  .sort((a, b) => a - b);

const rows = [];
for (const season of seasonDirs) {
  const seasonTitle = seasonTitles[String(season)];
  if (!seasonTitle) throw new Error(`Missing season title for Season ${season} in src/domain/seasonTitles.json.`);
  const file = path.join(contentRoot, `season-${String(season).padStart(2, '0')}`, 'chapters.ts');
  const bodies = parseBodies(await readFile(file, 'utf8'), season);
  for (let number = 1; number <= 10; number += 1) {
    const body = bodies.get(number);
    rows.push({
      id: `s${season}-e${number}`,
      number,
      season,
      seasonTitle,
      title: deriveTitle(body, number),
      summary: deriveSummary(body),
      status: 'Published',
      pov: 'Ensemble',
      tags: ['full prose', `Season ${season}`],
    });
  }
}

const serialized = rows.map((row) => `  ${JSON.stringify(row)},`).join('\n');
const output = `// AUTO-GENERATED by scripts/generate-manifest.mjs. Do not edit by hand.\nimport type { Chapter } from '../features/chapters/types';\n\nexport const manuscriptChapterManifest: Chapter[] = [\n${serialized}\n];\n`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, 'utf8');
console.log(`Generated ${rows.length} lightweight manuscript chapter records at ${path.relative(root, outputPath)}.`);
